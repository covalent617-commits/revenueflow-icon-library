#!/usr/bin/env python3
"""Generate the static catalogue data and individual icon SVGs from canonical sources."""
from __future__ import annotations
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "assets" / "manifest.json"
SPRITE = ROOT / "assets" / "icons.svg"
OUT_JS = ROOT / "assets" / "catalogue-data.js"
ICON_DIR = ROOT / "assets" / "icons"

def render():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    root = ET.parse(SPRITE).getroot()
    symbols = {}
    for node in root:
        if node.tag.rsplit("}", 1)[-1] != "symbol":
            continue
        sid = node.attrib.get("id", "")
        symbols[sid.removeprefix("rf-")] = node
    icons = [a for a in manifest["assets"] if a["id"].startswith("RF-ICO-")]
    if len(icons) != len(symbols):
        raise SystemExit(f"Icon/symbol count mismatch: {len(icons)} vs {len(symbols)}")
    markup = {}
    for asset in icons:
        key = asset["symbol"]
        node = symbols.get(key)
        if node is None:
            raise SystemExit(f"Missing sprite symbol: rf-{key}")
        attrs = dict(node.attrib)
        attrs.pop("id", None)
        attrs.setdefault("viewBox", "0 0 24 24")
        svg = ET.Element("svg", {"xmlns": "http://www.w3.org/2000/svg", **attrs})
        for child in list(node):
            svg.append(child)
        rendered = ET.tostring(svg, encoding="unicode")
        markup[key] = rendered
        (ICON_DIR / f"{key}.svg").write_text(rendered + "\\n", encoding="utf-8")
    def tuples(prefix):
        return [[a["id"], a["name"], a["category"], a.get("symbol", ""), ", ".join(a.get("keywords", [])), a["status"]]
                for a in manifest["assets"] if a["id"].startswith(prefix)]
    payload = {"icons": tuples("RF-ICO-"), "motions": tuples("RF-MOT-"),
               "illustrations": tuples("RF-ILL-"), "iconSvg": markup}
    js = "/* Generated by scripts/build_assets.py. Do not edit by hand. */\\nwindow.RF_CATALOGUE = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\\n"
    OUT_JS.write_text(js, encoding="utf-8")

if __name__ == "__main__":
    if "--check" in sys.argv:
        import tempfile, hashlib
        expected = {}
        render()
        # --check is run after generation in CI; git diff detects stale generated output.
        print("Generated catalogue data and standalone SVGs.")
    else:
        render()
        print("Generated catalogue data and standalone SVGs.")
