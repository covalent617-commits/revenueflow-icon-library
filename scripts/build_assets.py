#!/usr/bin/env python3
"""Generate catalogue data and individual SVG files from canonical sources."""
from __future__ import annotations
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "assets/manifest.json"
SPRITE = ROOT / "assets/icons.svg"
OUT_JS = ROOT / "assets/catalogue-data.js"
ICON_DIR = ROOT / "assets/icons"

def main() -> None:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    sprite = SPRITE.read_text(encoding="utf-8")
    symbols = {}
    for attrs, body in re.findall(r"<symbol\b([^>]*)>([\s\S]*?)</symbol>", sprite):
        sid = re.search(r'\bid="([^"]+)"', attrs)
        view_box = re.search(r'\bviewBox="([^"]+)"', attrs)
        if not sid:
            raise SystemExit("SVG symbol is missing an id")
        key = sid.group(1).removeprefix("rf-")
        vb = view_box.group(1) if view_box else "0 0 24 24"
        rest = re.sub(r'\bid="[^"]+"', "", attrs)
        rest = re.sub(r'\bviewBox="[^"]+"', "", rest).strip()
        symbols[key] = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" {rest}>{body}</svg>'
    icons = [a for a in manifest["assets"] if a["id"].startswith("RF-ICO-")]
    if len(icons) != len(symbols):
        raise SystemExit(f"Icon/symbol count mismatch: {len(icons)} vs {len(symbols)}")
    for asset in icons:
        key = asset["symbol"]
        if key not in symbols:
            raise SystemExit(f"Missing sprite symbol: rf-{key}")
        (ICON_DIR / f"{key}.svg").write_text(symbols[key] + "\n", encoding="utf-8")
    def tuples(prefix: str):
        return [[a["id"], a["name"], a["category"], a.get("symbol", ""),
                 ", ".join(a.get("keywords", [])), a["status"]]
                for a in manifest["assets"] if a["id"].startswith(prefix)]
    illustrations = [a for a in manifest["assets"] if a["id"].startswith("RF-ILL-")]
    illustration_svg = {}
    for asset in illustrations:
        path = ROOT / asset["source"]
        if not path.is_file():
            raise SystemExit(f"Missing illustration source: {asset['source']}")
        illustration_svg[asset["symbol"]] = path.read_text(encoding="utf-8").strip()
    payload = {"icons": tuples("RF-ICO-"), "motions": tuples("RF-MOT-"),
               "illustrations": tuples("RF-ILL-"),
               "iconSvg": {a["symbol"]: symbols[a["symbol"]] for a in icons},
               "illustrationSvg": illustration_svg}
    js = "/* Generated by scripts/build_assets.py. Do not edit by hand. */\nwindow.RF_CATALOGUE = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n"
    OUT_JS.write_text(js, encoding="utf-8")
    print(f"Generated {len(icons)} standalone icons and catalogue data for {len(manifest['assets'])} assets.")

if __name__ == "__main__":
    main()
